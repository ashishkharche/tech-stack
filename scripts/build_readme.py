def icon_img(app: App, rel: str, size: int) -> str:
    src = app.icon()
    if not src:  # build() leaves apps without a verified icon out, so this is a bug if it happens
        raise SystemExit(f"no verified icon for {app.rel}")
    return f'<img src="{rel}{src}" width="{size}" height="{size}" alt="{h(short_name(app.name))} icon">'


def grid(apps: list[App], rel: str, caption, cols: int = 6, size: int = 56) -> str:
    rows, cells = [], []
    for app in apps:
        cells.append(f'<td align="center" valign="top" width="{int(100 / cols)}%">'
                     f'<a href="{rel}{app.rel}/README.md">{icon_img(app, rel, size)}</a><br>'
                     f'<a href="{rel}{app.rel}/README.md"><sub><b>{h(short_name(app.name))}</b></sub></a><br>'
                     f'<sub>{h(caption(app))}</sub></td>')
        if len(cells) == cols:
            rows.append("<tr>" + "".join(cells) + "</tr>")
            cells = []
    if cells:
        rows.append("<tr>" + "".join(cells) + "</tr>")
    return "<table>\n" + "\n".join(rows) + "\n</table>"


WRITTEN_CHARTS: set[str] = set()


def write_chart(name: str, fn, *args, **kw):
    WRITTEN_CHARTS.add(name)
    for theme in ("light", "dark"):
        write(ROOT / CHARTS / f"{name}-{theme}.svg", fn(*args, theme=theme, **kw))


def platform_split(items, key):
    """Counter of key(item) -> [ios, android]."""
    out: dict[str, list[int]] = defaultdict(lambda: [0, 0])
    for app in items:
        for k in key(app):
            out[k][0 if app.platform == "ios" else 1] += 1
    return out


def sdk_changes(app: App):
    """[(older_version, newer_version, added, removed)] for consecutive versions, oldest first."""
    out = []
    docs = list(reversed(app.docs))
    for older, newer in zip(docs, docs[1:]):
        a = {s["name"] for s in older["stack"]["sdks"]}
        b = {s["name"] for s in newer["stack"]["sdks"]}
        out.append((older["version"], newer["version"], sorted(b - a, key=str.lower), sorted(a - b, key=str.lower)))
    return out


