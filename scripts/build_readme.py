BLOCK_RE = re.compile(r"(<!-- ts:begin ([a-z0-9-]+) -->)(.*?)(<!-- ts:end \2 -->)", re.S)


def fill(text: str, blocks: dict[str, str]) -> str:
    def rep(m):
        name = m.group(2)
        if name not in blocks:
            return m.group(0)
        return f"{m.group(1)}\n{blocks[name]}\n{m.group(4)}"
    return BLOCK_RE.sub(rep, text)


