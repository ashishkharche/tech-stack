def build(root: Path = ROOT) -> dict:
    ICON_SOURCES.clear()
    ICON_SOURCES.update(load_sources())
    loaded = load_apps(root)
    # An app with no verified store icon is left out of the README, charts and lists (never a
    # placeholder), and flagged here so it can be fixed with scripts/icons.py.
    apps = [p for p in loaded if p.icon()]
    no_icon = [p for p in loaded if not p.icon()]
    for p in no_icon:
        print(f"FLAG no verified icon, left out: {p.rel} ({p.name})", file=sys.stderr)
        stale = p.dir / "README.md"
        if stale.exists():
            stale.unlink()
    ios, andr, companies, sdk_apps, stats = compute(apps)
    build_brand(stats)
    facts = build_charts(apps, ios, andr, companies, sdk_apps, stats)

    wanted_charts: set[str] = set()
    for p in apps:
        write(p.dir / "README.md", app_page(p, wanted_charts))
    comp_dir = root / "companies"
    wanted = {"README.md"}
    for slug, grp in sorted(companies.items()):
        wanted.add(f"{slug}.md")
        write(comp_dir / f"{slug}.md", company_page(slug, grp, wanted_charts))
    write(comp_dir / "README.md", companies_index(companies))
    for old in comp_dir.glob("*.md"):
        if old.name not in wanted:
            old.unlink()
    for old in (root / CHARTS).glob("*.svg"):
        if old.name.rsplit("-", 1)[0] not in WRITTEN_CHARTS:
            old.unlink()
    for sub in ("apps", "companies"):
        for old in (root / CHARTS / sub).rglob("*.svg"):
            if old.relative_to(root).as_posix() not in wanted_charts:
                old.unlink()

    blocks = readme_blocks(apps, ios, andr, companies, sdk_apps, stats, facts)
    readme = root / "README.md"
    current = readme.read_text() if readme.exists() else ""
    base = current if "<!-- ts:begin header -->" in current else TEMPLATE.read_text()
    write(readme, fill(base, blocks))
    stats["left_out_no_icon"] = [p.rel for p in no_icon]
    stats["charts"] = sorted(x.name.removesuffix("-light.svg") for x in (root / CHARTS).glob("*-light.svg"))
    if K.ISSUES:
        for issue in K.ISSUES:
            print(f"layout: {issue}", file=sys.stderr)
        raise SystemExit(f"{len(K.ISSUES)} chart layout problem(s); fix svgkit.py layout before committing")
    return stats


