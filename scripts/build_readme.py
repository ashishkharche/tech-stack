def png(svg_path: Path, png_path: Path, width: int) -> bool:
    exe = shutil.which("rsvg-convert")
    if not exe:
        print(f"rsvg-convert not found; kept existing {png_path.name}")
        return False
    tmp = png_path.with_suffix(".tmp.png")
    subprocess.run([exe, "-w", str(width), str(svg_path), "-o", str(tmp)], check=True)
    if png_path.exists() and png_path.read_bytes() == tmp.read_bytes():
        tmp.unlink()
    else:
        tmp.replace(png_path)
    return True


def build_brand(stats):
    a = ROOT / ASSETS
    # Iso Block logo: black on light backgrounds, white on dark. 512px PNGs plus 32px favicon sizes.
    logo = a / "logo"
    for theme in ("light", "dark"):
        write(logo / f"logo-{theme}.svg", K.logo_svg(theme))
        png(logo / f"logo-{theme}.svg", logo / f"logo-{theme}.png", 512)
        png(logo / f"logo-{theme}.svg", logo / f"favicon-{theme}-32.png", 32)
    badges = a / "badges"
    for fname, label, filled in BADGES:
        for theme in ("light", "dark"):
            write(badges / f"{fname}-{theme}.svg",
                  K.badge_svg(label, theme, filled=filled, platform=fname if fname in PLATFORM else None))


