# ---------------------------------------------------------------- helpers

def cat_label(c: str) -> str:
    return CATEGORY_LABELS.get(c, c.replace("_", " ").capitalize())


def md(s) -> str:
    return str(s if s is not None else "").replace("|", "\\|").replace("\n", " ")


def h(s) -> str:
    return K.x(s)


def short_name(name: str) -> str:
    """Display name for grids: the part before ':' / ' - ' / ' – ', when that part is not empty."""
    for sep in (":", " - ", " – ", " — ", " | "):
        if sep in name:
            head = name.split(sep, 1)[0].strip()
            if len(head) >= 2:
                name = head
    return name


def store_url(a) -> str:
    if a["platform"] == "ios":
        return f"https://apps.apple.com/app/id{a['store_id']}"
    return f"https://play.google.com/store/apps/details?id={a['store_id']}"


def write(path: Path, text: str) -> bool:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text() == text:
        return False
    path.write_text(text)
    return True


def themed(rel: str, stem: str, alt: str, width: int | None = None) -> str:
    """<picture> that shows `stem`-dark.svg in dark mode and `stem`-light.svg otherwise. Both variants sit
    on their own solid background, so either one also reads on the other theme."""
    w = f' width="{width}"' if width else ""
    return (f'<picture><source media="(prefers-color-scheme: dark)" srcset="{rel}{stem}-dark.svg">'
            f'<img alt="{h(alt)}" src="{rel}{stem}-light.svg"{w}></picture>')


def picture(rel: str, name: str, alt: str, width: int | None = None) -> str:
    return themed(rel, f"{CHARTS}/{name}", alt, width)


class App:
    def __init__(self, app_dir: Path, docs: list[dict]):
        self.dir = app_dir
        self.rel = app_dir.relative_to(ROOT).as_posix()
        self.docs = docs  # newest version first
        self.latest = docs[0]
        self.a = self.latest["app"]
        self.platform = self.a["platform"]
        self.sdks = self.latest["stack"]["sdks"]
        self.sdk_names = {s["name"] for s in self.sdks}

    @property
    def name(self):
        return self.a["name"]

    @property
    def captured(self):
        return self.latest["dates"]["captured_at"] or ""

    def icon(self) -> str | None:
        """The cached store icon, only when its source is on record (data/icon-sources.csv)."""
        p = verified_icon(self.platform, self.a["store_id"], ICON_SOURCES)
        return p.relative_to(ROOT).as_posix() if p else None


def load_apps(root: Path) -> list[App]:
    groups: dict[Path, list[dict]] = defaultdict(list)
    for path in sorted((root / "apps").glob("*/*/*/*.json")):
        if path.name == "latest.json":
            continue
        d = json.loads(path.read_text())
        d["_file"] = path.name
        groups[path.parent].append(d)

    def cmp(a, b):
        c = compare_versions(a["version"], b["version"])
        if c:
            return c
        ca, cb = a["dates"]["captured_at"] or "", b["dates"]["captured_at"] or ""
        return (ca > cb) - (ca < cb)

    apps = []
    for app_dir, docs in sorted(groups.items()):
        docs.sort(key=cmp_to_key(cmp), reverse=True)
        apps.append(App(app_dir, docs))
    return apps


