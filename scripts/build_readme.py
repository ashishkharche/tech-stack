def nav(rel, *crumbs):
    parts = [f"[Tech Stack]({rel}README.md)"] + list(crumbs)
    mark = (f'<picture><source media="(prefers-color-scheme: dark)" srcset="{rel}{LOGO}/logo-dark.svg">'
            f'<img src="{rel}{LOGO}/logo-light.svg" width="14" height="14" alt=""></picture>')
    return f"<sub>{mark} " + " / ".join(parts) + "</sub>"


def category_chart(sdks, stem: str, label: str, wanted: set[str], series=("SDKs",)) -> bool:
    """Writes `stem`-light.svg and `stem`-dark.svg (stem is relative to the repo root)."""
    cats = Counter(s["category"] for s in sdks)
    if not cats:
        return False
    rows = [(cat_label(k), [v]) for k, v in sorted(cats.items(), key=lambda kv: (-kv[1], kv[0]))]
    for theme in ("light", "dark"):
        write(ROOT / f"{stem}-{theme}.svg", K.hbar(rows, theme, series=series, width=640, bar_h=14, gap=8, label=label))
        wanted.add(f"{stem}-{theme}.svg")
    return True


def app_page(p: App, wanted_charts: set[str]) -> str:
    rel = "../../../../"
    a, d, st = p.a, p.latest, p.latest["stack"]
    comp = a["company"]
    cname = comp["name"]
    badges = [badge(rel, p.platform, PLATFORM[p.platform]),
              badge(rel, "active" if a["active"] else "inactive", "Tracked" if a["active"] else "No longer tracked")]
    if d["confidence"]["sdk_list_is_floor"]:
        badges.append(badge(rel, "floor", "SDK list is a floor"))
    if d["confidence"]["binary_encrypted"]:
        badges.append(badge(rel, "encrypted", "Binary encrypted"))
    lines = [nav(rel, f"[{md(cname)}]({rel}companies/{comp['slug']}.md)", md(short_name(a["name"]))), "",
             icon_img(p, rel, 96), "", f"# {md(a['name'])}", "", " ".join(badges), "",
             f"[{STORE[p.platform]}]({store_url(a)}) · [latest.json](latest.json)", ""]
    pf = st["platform"]
    if p.platform == "ios":
        os_line = f"iOS {pf['min_os']}" if pf.get("min_os") else ""
        if pf.get("xcode"):
            os_line += f" (built with Xcode {pf['xcode']}, SDK {pf.get('build_sdk') or '?'})"
    else:
        os_line = f"API {pf['min_sdk']}" if pf.get("min_sdk") else (pf.get("min_os") or "")
        if pf.get("target_sdk"):
            os_line += f", targets API {pf['target_sdk']}"
    facts = [
        ("Company", f"[{md(cname)}]({rel}companies/{comp['slug']}.md)"),
        ("Store id", f"`{a['store_id']}`"), ("Bundle / package id", f"`{a['bundle_id'] or ''}`"),
        ("Latest version", md(d['version']) + (f" (analysed {d['dates']['captured_at'][:10]})" if d['dates']['captured_at'] else "")),
        ("Versions tracked", str(len(p.docs))),
        ("SDKs in latest version", str(st["sdk_count"])),
        ("Languages", md(", ".join(st["languages"]))),
        ("UI", md(", ".join(st["ui_graphics"]))),
        ("Build", md(", ".join(st["build_system"]))),
        ("Minimum OS", md(os_line)),
        ("Devices / ABIs", md(", ".join(pf.get("device_families") or pf.get("abis") or []))),
        ("Localisations", str(pf["localization_count"]) if pf.get("localization_count") is not None else ""),
        ("Capabilities", str(len(st["capabilities"]))),
        ("Declares tracking", {True: "Yes", False: "No"}.get(st["privacy"]["declares_tracking"], "")),
        ("Tracked", "Yes" if a["active"] else "No. Kept for history."),
    ]
    lines += ["| | |", "|---|---|"] + [f"| {k} | {v} |" for k, v in facts if v not in ("", None)] + [""]

    if st["sdks"]:
        chart = f"{CHARTS}/apps/{p.rel.removeprefix('apps/')}"
        category_chart(st["sdks"], chart, f"{a['name']} SDKs by category", wanted_charts,
                       series=(f"{PLATFORM[p.platform]} SDKs",))
        lines += ["## SDKs by category", "", themed(rel, chart, "SDKs by category"), ""]
        bycat = defaultdict(list)
        for s in st["sdks"]:
            bycat[s["category"]].append(s)
        for cat, items in sorted(bycat.items(), key=lambda kv: (-len(kv[1]), kv[0])):
            names = ", ".join(md(s["name"]) + (f" {md(s['version'])}" if s.get("version") else "") for s in sorted(items, key=lambda s: s["name"].lower()))
            lines.append(f"- **{cat_label(cat)}** ({len(items)}): {names}")
        lines.append("")

    if st["frameworks"]:
        lines += ["<details>", f"<summary>Frameworks ({len(st['frameworks'])})</summary>", "",
                  md(", ".join(st["frameworks"])), "", "</details>", ""]
    if st["capabilities"]:
        lines += ["<details>", f"<summary>Capabilities ({len(st['capabilities'])})</summary>", "",
                  md(", ".join(st["capabilities"])), "", "</details>", ""]

    changes = {newer: (add, rem) for _, newer, add, rem in sdk_changes(p)}
    lines += ["## Version history", "",
              "| Version | Analysed | Store update | SDKs | Change | SDK list is a floor | Binary encrypted | File |",
              "|---|---|---|---|---|---|---|---|"]
    for v in p.docs:
        c = v["confidence"]
        add, rem = changes.get(v["version"], (None, None))
        ch = "" if add is None else f"+{len(add)} / −{len(rem)}"
        lines.append(f"| {md(v['version'])} | {(v['dates']['captured_at'] or '')[:10]} | {(v['dates']['store_updated_at'] or '')[:10]} | "
                     f"{v['stack']['sdk_count']} | {ch} | {'Yes' if c['sdk_list_is_floor'] else 'No'} | "
                     f"{'Yes' if c['binary_encrypted'] else 'No'} | [{v['_file']}]({v['_file']}) |")
    lines.append("")
    real = [(o, n, ad, rm) for o, n, ad, rm in sdk_changes(p) if ad or rm]
    if real:
        lines += ["### SDK changes between versions", ""]
        for o, n, ad, rm in reversed(real):
            bits = []
            if ad:
                bits.append("added " + ", ".join(md(x) for x in ad))
            if rm:
                bits.append("removed " + ", ".join(md(x) for x in rm))
            lines.append(f"- {md(o)} → {md(n)}: " + "; ".join(bits))
        lines.append("")

    inf = [i for i in d.get("inferred") or [] if i.get("headline")]
    if inf:
        lines += ["## Model-written summary", "", "> " + md(inf[0]["headline"]), "",
                  "<sub>Written by a language model from the detected signals (`inferred[]`). It is commentary, not measurement.</sub>", ""]
    lines += ["---", "", f"<sub>{FOOTER}</sub>", ""]
    return "\n".join(lines)


def company_page(slug: str, grp: list[App], wanted_charts: set[str]) -> str:
    rel = "../"
    title = grp[0].a["company"]["name"]
    grp = sorted(grp, key=lambda p: (p.name.lower(), p.platform))
    n_ios = sum(p.platform == "ios" for p in grp)
    distinct = {s["name"].lower(): s["name"] for p in grp for s in p.sdks}
    lines = [nav(rel, "[Companies](README.md)", md(title)), "", f"# {md(title)}", ""]
    lines += ["The company name is the developer name on the store listing.", ""]
    lines += [f"**{len(grp)}** apps ({n_ios} iOS, {len(grp) - n_ios} Android) · **{sum(len(p.docs) for p in grp)}** versions · "
              f"**{len(distinct)}** distinct SDKs across their latest versions", ""]
    if len(grp) <= 36:
        lines += [grid(grp, rel, lambda p: f"{PLATFORM[p.platform]} · {p.latest['stack']['sdk_count']} SDKs"), ""]
    lines += ["## Apps", "", "| | App | Platform | Versions | Latest | Analysed | SDKs | Tracked |", "|---|---|---|---|---|---|---|---|"]
    for p in grp:
        lines.append(f"| {icon_img(p, rel, 20)} | [{md(p.name)}](../{p.rel}/README.md) | {PLATFORM[p.platform]} | {len(p.docs)} | "
                     f"{md(p.latest['version'])} | {p.captured[:10]} | {p.latest['stack']['sdk_count']} | {'Yes' if p.a['active'] else 'No'} |")
    lines.append("")
    all_sdks = [s for p in grp for s in p.sdks]
    if all_sdks:
        chart = f"{CHARTS}/companies/{slug}"
        category_chart(all_sdks, chart, f"{title} SDKs by category", wanted_charts)
        lines += ["## SDKs by category", "", "Counted across the latest version of each app.", "",
                  themed(rel, chart, "SDKs by category"), ""]
    if len(grp) > 1:
        cnt = Counter(s["name"].lower() for p in grp for s in {x["name"].lower(): x for x in p.sdks}.values())
        shared = [(distinct[k], v) for k, v in cnt.items() if v > 1]
        shared.sort(key=lambda kv: (-kv[1], kv[0].lower()))
        if shared:
            lines += ["## SDKs shared across their apps", "", "| SDK | Apps |", "|---|---|"]
            lines += [f"| {md(n)} | {v} of {len(grp)} |" for n, v in shared[:20]] + [""]
    lines += ["---", "", f"<sub>{FOOTER}</sub>", ""]
    return "\n".join(lines)


def companies_index(companies) -> str:
    rel = "../"
    rows = sorted(companies.items(), key=lambda kv: (-len(kv[1]), (kv[1][0].a["company"]["name"] or "").lower()))
    lines = [nav(rel, "Companies"), "", "# Companies", "",
             f"{len(rows)} companies. Each name is the developer name on the store listing.", "",
             "| | Company | Apps | iOS | Android | Versions | SDKs (distinct) |", "|---|---|---|---|---|---|---|"]
    for slug, grp in rows:
        name = grp[0].a["company"]["name"]
        icons = " ".join(icon_img(p, rel, 20) for p in sorted(grp, key=lambda p: p.name.lower())[:5])
        lines.append(f"| {icons} | [{md(name)}]({slug}.md) | {len(grp)} | {sum(p.platform == 'ios' for p in grp)} | "
                     f"{sum(p.platform == 'android' for p in grp)} | {sum(len(p.docs) for p in grp)} | "
                     f"{len({s['name'].lower() for p in grp for s in p.sdks})} |")
    lines += ["", "---", "", f"<sub>{FOOTER}</sub>", ""]
    return "\n".join(lines)


